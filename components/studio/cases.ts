export const HR_CASE_H = HR_BOARDS.reduce((s, b) => s + b.h, 0);
export const boardTop = (id: HrBoardId) => {
  let y = 0;
  for (const b of HR_BOARDS) {
    if (b.id === id) return y;
    y += b.h;
  }
  return y;
};
